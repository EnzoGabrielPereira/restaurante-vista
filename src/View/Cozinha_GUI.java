private void carregarPedidos() {
    DefaultTableModel modelo = new DefaultTableModel(
            new String[]{"Mesa", "Pedido", "Observação", "Quantidade"}, 0) {
        @Override
        public boolean isCellEditable(int linha, int coluna) {
            return false; // a cozinha só visualiza
        }
    };

    String sql = "SELECT c.num_mesa, p.prato, p.observacao, p.quantidade "
               + "FROM pedido p "
               + "JOIN comanda c ON c.id_comanda = p.id_comanda "
               + "ORDER BY p.id_pedido";

    try (Connection con = DriverManager.getConnection(url, username, password);
         PreparedStatement pst = con.prepareStatement(sql);
         ResultSet rs = pst.executeQuery()) {

        while (rs.next()) {
            modelo.addRow(new Object[]{
                rs.getInt("num_mesa"),
                rs.getString("prato"),
                rs.getString("observacao"),
                rs.getInt("quantidade")
            });
        }
        tab_caixa.setModel(modelo);

    } catch (Exception ex) {
        System.err.println("Erro ao carregar pedidos da cozinha: " + ex.getMessage());
    }
}
    
    

